import re
import numpy as np
import pandas as pd


def clean_with_chatgpt_zero_shot(df_input: pd.DataFrame) -> tuple[pd.DataFrame, list[str]]:
    """
    Simulates typical code generated by ChatGPT (Free Tier / Zero-Shot) when prompted:
    'Write Python pandas code to clean this messy customer dataset. Fix missing values,
     data types, duplicates, and outliers.'
     
    Exhibits classic LLM data cleaning anti-patterns:
    - Blind dropna() causing severe silent data loss
    - Naive regex stripping legitimate name characters (hyphens, apostrophes)
    - Day/month date swap on European formats
    - Inability to parse '75k' currency shorthands
    - Destruction of valid negative refund transactions
    - Unaware of demographic bias in mean imputation
    """
    df = df_input.copy()
    runtime_notes = []

    # 1. Duplicates: AI usually does simple drop_duplicates without string stripping
    initial_len = len(df)
    df.drop_duplicates(inplace=True)
    runtime_notes.append(f"Deduplication (untrimmed): removed {initial_len - len(df)} rows.")

    # 2. String cleaning with overzealous regex (strips apostrophes and hyphens!)
    if "full_name" in df.columns:
        # AI anti-pattern: removes all non-alphabet characters
        df["full_name"] = df["full_name"].astype(str).str.replace(r"[^a-zA-Z\s]", "", regex=True).str.strip().str.title()
        df["full_name"] = df["full_name"].replace("Nan", np.nan)
        runtime_notes.append("Cleaned full_name using naive regex: r'[^a-zA-Z\\s]' (Corrupts O'Connor, Jean-Luc).")

    # 3. Customer ID: simple strip
    if "customer_id" in df.columns:
        df["customer_id"] = df["customer_id"].astype(str).str.strip().str.upper()
        df["customer_id"] = df["customer_id"].replace("NAN", np.nan)

    # 4. Age cleaning: coercing numeric and dropping negative/outliers
    if "age" in df.columns:
        # Extract digits only
        df["age"] = df["age"].astype(str).str.extract(r"(\d+)")[0]
        df["age"] = pd.to_numeric(df["age"], errors="coerce")
        # Mean imputation
        mean_age = df["age"].mean()
        df["age"] = df["age"].fillna(mean_age).round()

    # 5. Gender: simple uppercase/lowercase
    if "gender" in df.columns:
        gender_map = {"F": "Female", "M": "Male", "FEMALE": "Female", "MALE": "Male"}
        df["gender"] = df["gender"].astype(str).str.strip().replace(gender_map)
        df["gender"] = df["gender"].replace({"nan": np.nan, "Nan": np.nan, "None": np.nan})

    # 6. Country: basic mapping
    if "country" in df.columns:
        country_map = {"US": "United States", "USA": "United States", "UK": "United Kingdom"}
        df["country"] = df["country"].astype(str).str.strip().replace(country_map)
        df["country"] = df["country"].replace({"nan": np.nan, "Nan": np.nan})

    # 7. Signup Date: pd.to_datetime with default dayfirst=False (causes month/day flip)
    if "signup_date" in df.columns:
        # Default dayfirst=False swaps European dates like 15/01/2023 to NaT or 04/05/2023 to April 5 instead of May 4
        df["signup_date"] = pd.to_datetime(df["signup_date"], errors="coerce", dayfirst=False)
        df["signup_date"] = df["signup_date"].dt.strftime("%Y-%m-%d")
        runtime_notes.append("Parsed signup_date with default dayfirst=False (flips DD/MM to MM/DD).")

    # 8. Annual Income: AI replaces '$' and ',' but fails on 'k' shorthand (e.g. '75k')
    if "annual_income" in df.columns:
        income_str = df["annual_income"].astype(str).str.replace("$", "", regex=False).str.replace(",", "", regex=False).str.replace("USD", "", regex=False).str.strip()
        df["annual_income"] = pd.to_numeric(income_str, errors="coerce")
        # Global mean imputation (skews distributions)
        df["annual_income"] = df["annual_income"].fillna(df["annual_income"].mean())
        runtime_notes.append("Parsed annual_income: 'k' abbreviations turned to NaN; filled with global mean.")

    # 9. Purchase Amount: AI drops negative numbers thinking they are errors (destroys refunds!)
    if "purchase_amount" in df.columns:
        pur_str = df["purchase_amount"].astype(str).str.replace("$", "", regex=False).str.replace(",", "", regex=False).str.replace("EUR", "", regex=False).str.strip()
        df["purchase_amount"] = pd.to_numeric(pur_str, errors="coerce")
        # AI anti-pattern: treats negatives as erroneous and takes abs() or filters > 0
        df["purchase_amount"] = df["purchase_amount"].abs()  # Destroys refund semantics
        # Outlier clipping: anything > 10,000 set to median
        median_pur = df["purchase_amount"].median()
        df.loc[df["purchase_amount"] > 10000, "purchase_amount"] = median_pur
        runtime_notes.append("Applied abs() to purchase_amount (erased negative refund flags).")

    # 10. Transaction Count
    if "transaction_count" in df.columns:
        df["transaction_count"] = pd.to_numeric(df["transaction_count"], errors="coerce")
        df["transaction_count"] = df["transaction_count"].fillna(1).clip(lower=1, upper=50).astype(int)

    # 11. Email: simple lowercase
    if "email" in df.columns:
        df["email"] = df["email"].astype(str).str.strip().str.lower()
        # Drop invalid emails without @
        df.loc[~df["email"].str.contains("@", na=False), "email"] = np.nan

    # 12. Satisfaction Score
    if "satisfaction_score" in df.columns:
        # AI extract digits
        df["satisfaction_score"] = df["satisfaction_score"].astype(str).str.extract(r"(\d+)")[0]
        df["satisfaction_score"] = pd.to_numeric(df["satisfaction_score"], errors="coerce")
        df["satisfaction_score"] = df["satisfaction_score"].clip(lower=1, upper=5).fillna(3).astype(int)

    # 13. Churn: basic mapping
    if "churn" in df.columns:
        churn_map = {"1": "Yes", "0": "No", "TRUE": "Yes", "FALSE": "No", "true": "Yes", "false": "No", "yes": "Yes", "no": "No"}
        df["churn"] = df["churn"].astype(str).str.strip().replace(churn_map)
        df["churn"] = df["churn"].replace({"nan": np.nan, "Nan": np.nan})

    # 14. FATAL AI ANTI-PATTERN: Blind dropna()
    # ChatGPT frequently outputs `df.dropna(inplace=True)` at the end of the cleaning script
    before_dropna = len(df)
    df.dropna(inplace=True)
    dropped_count = before_dropna - len(df)
    runtime_notes.append(f"FATAL: Global dropna() eliminated {dropped_count} rows ({dropped_count/before_dropna*100:.1f}%) due to optional phone_number/missing fields.")

    return df.reset_index(drop=True), runtime_notes


def clean_with_gemini_engineered(df_input: pd.DataFrame) -> tuple[pd.DataFrame, list[str]]:
    """
    Simulates code generated by Gemini Flash with Prompt Engineering (Few-Shot & Schema Constraints):
    - Instructed NOT to drop rows for optional phone numbers
    - Retains negative refund amounts
    - Normalizes abbreviations
    
    Exhibits higher reliability, but still contains subtle edge cases:
    - Edge cases in country mappings ('Deutschland', 'Oz')
    - Month-day ambiguity on multi-format dates
    - Naive median imputation without subgroup awareness
    """
    df = df_input.copy()
    runtime_notes = []

    # 1. Trimming string fields before deduplication
    str_cols = df.select_dtypes(include=["object"]).columns
    for c in str_cols:
        df[c] = df[c].astype(str).str.strip()
        df[c] = df[c].replace({"nan": np.nan, "None": np.nan, "NaN": np.nan, "NULL": np.nan})

    # Drop fully empty rows
    df.dropna(how="all", inplace=True)

    # Deduplicate on customer_id if present, else subset
    initial_len = len(df)
    df.drop_duplicates(subset=["customer_id"], keep="first", inplace=True)
    runtime_notes.append(f"Deduplicated by trimmed customer_id: removed {initial_len - len(df)} duplicate rows.")

    # 2. Customer Name: Title case, preserve hyphens and apostrophes
    if "full_name" in df.columns:
        # Removes honorific prefixes like Dr., Mr., Ms.
        df["full_name"] = df["full_name"].astype(str).str.replace(r"^(Dr\.|Mr\.|Ms\.|Prof\.)\s+", "", regex=True)
        # Safe title casing preserving hyphens and apostrophes
        def safe_title(val):
            if pd.isna(val) or str(val).lower() in ["nan", "none"]:
                return np.nan
            return " ".join([part.capitalize() for part in str(val).split(" ")])
        df["full_name"] = df["full_name"].apply(safe_title)
        runtime_notes.append("Cleaned full_name preserving internal hyphens/apostrophes.")

    # 3. Customer ID formatting
    if "customer_id" in df.columns:
        df["customer_id"] = df["customer_id"].astype(str).str.upper()

    # 4. Age: parse and handle negative values by abs()
    if "age" in df.columns:
        df["age"] = df["age"].astype(str).str.extract(r"(-?\d+)")[0]
        df["age"] = pd.to_numeric(df["age"], errors="coerce")
        df["age"] = df["age"].abs()
        # Cap unreasonable outliers (100+) with median
        valid_median = df.loc[(df["age"] >= 18) & (df["age"] <= 85), "age"].median()
        df.loc[(df["age"] < 18) | (df["age"] > 85), "age"] = valid_median
        df["age"] = df["age"].fillna(valid_median).astype(int)

    # 5. Gender: normalized dictionary
    if "gender" in df.columns:
        gender_lookup = {
            "f": "Female", "female": "Female", "fem": "Female",
            "m": "Male", "male": "Male", "mal": "Male",
            "nb": "Non-Binary", "non-binary": "Non-Binary", "non binary": "Non-Binary"
        }
        df["gender"] = df["gender"].astype(str).str.lower().map(gender_lookup).fillna("Prefer not to say")

    # 6. Country: expanded dictionary
    if "country" in df.columns:
        country_lookup = {
            "us": "United States", "usa": "United States", "u.s.a.": "United States", "u.s.": "United States", "united states": "United States",
            "uk": "United Kingdom", "u.k.": "United Kingdom", "great britain": "United Kingdom", "gb": "United Kingdom", "united kingdom": "United Kingdom",
            "ca": "Canada", "can": "Canada", "canada": "Canada",
            "germany": "Germany", "ger": "Germany", "de": "Germany", "deutschland": "Germany",
            "au": "Australia", "aus": "Australia", "australia": "Australia", "oz": "Australia"
        }
        df["country"] = df["country"].astype(str).str.lower().map(country_lookup).fillna("Other")

    # 7. Signup Date: flexible parsing
    if "signup_date" in df.columns:
        # Prompt engineered AI adds errors='coerce' and dayfirst=True
        df["signup_date"] = pd.to_datetime(df["signup_date"], errors="coerce", dayfirst=True)
        # Forward fill or default to median date
        median_date = df["signup_date"].dropna().median()
        df["signup_date"] = df["signup_date"].fillna(median_date).dt.strftime("%Y-%m-%d")

    # 8. Annual Income: Handles '$', ',', 'USD', and 'k' multiplier!
    if "annual_income" in df.columns:
        def parse_income(val):
            if pd.isna(val):
                return np.nan
            s = str(val).lower().replace("$", "").replace(",", "").replace("usd", "").strip()
            if "k" in s:
                try:
                    return float(s.replace("k", "")) * 1000
                except ValueError:
                    return np.nan
            try:
                num = float(s)
                return abs(num) if num > 0 else np.nan
            except ValueError:
                return np.nan

        df["annual_income"] = df["annual_income"].apply(parse_income)
        income_median = df["annual_income"].median()
        df["annual_income"] = df["annual_income"].fillna(income_median).round(2)

    # 9. Purchase Amount: Preserves negative refund values, handles currency
    if "purchase_amount" in df.columns:
        def parse_purchase(val):
            if pd.isna(val):
                return np.nan
            s = str(val).lower().replace("$", "").replace(",", "").replace("eur", "").strip()
            if s in ["free", "refunded", "cancelled", "n/a", "none"]:
                return 0.0
            try:
                num = float(s)
                # Clip extreme typo outliers (e.g. 9,999,999)
                if abs(num) > 5000:
                    return np.nan
                return num
            except ValueError:
                return np.nan

        df["purchase_amount"] = df["purchase_amount"].apply(parse_purchase)
        pur_median = df["purchase_amount"].median()
        df["purchase_amount"] = df["purchase_amount"].fillna(pur_median).round(2)

    # 10. Transaction Count
    if "transaction_count" in df.columns:
        df["transaction_count"] = pd.to_numeric(df["transaction_count"], errors="coerce").fillna(1)
        df["transaction_count"] = df["transaction_count"].abs().clip(lower=1, upper=50).astype(int)

    # 11. Email
    if "email" in df.columns:
        df["email"] = df["email"].astype(str).str.lower().str.strip()
        valid_email_pattern = r"^[\w\.-]+@[\w\.-]+\.\w+$"
        invalid_mask = ~df["email"].str.match(valid_email_pattern, na=False)
        df.loc[invalid_mask, "email"] = np.nan

    # 12. Phone: keep as formatted string, DO NOT DROP
    if "phone_number" in df.columns:
        df["phone_number"] = df["phone_number"].astype(str).str.replace(r"[^\d+]", "", regex=True)
        df["phone_number"] = df["phone_number"].replace({"nan": "Not Provided", "": "Not Provided"})

    # 13. Satisfaction Score: convert text ratings
    if "satisfaction_score" in df.columns:
        text_ratings = {"very poor": 1, "poor": 2, "average": 3, "good": 4, "excellent": 5}
        def parse_sat(val):
            if pd.isna(val):
                return 3
            v = str(val).lower().strip()
            if v in text_ratings:
                return text_ratings[v]
            match = re.search(r"(\d+)", v)
            if match:
                num = int(match.group(1))
                return max(1, min(5, num))
            return 3
        df["satisfaction_score"] = df["satisfaction_score"].apply(parse_sat).astype(int)

    # 14. Churn
    if "churn" in df.columns:
        churn_lookup = {"1": "Yes", "0": "No", "true": "Yes", "false": "No", "yes": "Yes", "no": "No"}
        df["churn"] = df["churn"].astype(str).str.lower().map(churn_lookup).fillna("No")

    # Selective dropping only on crucial key (customer_id missing)
    before_drop = len(df)
    df = df[df["customer_id"].notna() & (df["customer_id"] != "NAN")]
    runtime_notes.append(f"Selective drop: dropped {before_drop - len(df)} rows with missing customer_id.")

    return df.reset_index(drop=True), runtime_notes
